export default function PixelIcon({ name, className = '' }) {
  const pattern = patterns[name];
  const columns = Math.max(...pattern.map((row) => row.length));
  return (
    <span className={`pixel-icon ${className}`} aria-hidden="true" style={{ gridTemplateColumns: `repeat(${columns}, 1fr)`, gridTemplateRows: `repeat(${pattern.length}, 1fr)` }}>
      {pattern.flatMap((row, y) => [...row].map((pixel, x) => pixel !== '.' && (
        <i key={`${x}-${y}`} style={{ gridColumn: x + 1, gridRow: y + 1, background: { w: '#fff0a3', b: '#9a481c', k: '#252b30', h: '#f1f5ff', v: '#8140dd', p: '#b67bff' }[pixel] }} />
      )))}
    </span>
  );
}
